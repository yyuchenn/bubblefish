use bubblefish_core::*;
use std::{fs, path::PathBuf};
use ts_rs::{Config, TS};

fn declarations() -> String {
    let cfg = Config::default();
    let declarations = [
        serde_json::Value::decl(&cfg),
        TextMark::decl(&cfg),
        TextRun::decl(&cfg),
        RichText::decl(&cfg),
        Geometry::decl(&cfg),
        MarkerStyle::decl(&cfg),
        Marker::decl(&cfg),
        ImageDocument::decl(&cfg),
        ProjectDocument::decl(&cfg),
        EditorBookmark::decl(&cfg),
        HistoryMeta::decl(&cfg),
        Command::decl(&cfg),
        Envelope::decl(&cfg),
        CoreError::decl(&cfg),
        ProjectPatch::decl(&cfg),
        Reply::decl(&cfg),
    ];
    let mut result = String::from("// Generated by `npm run types:generate`. Do not edit by hand.\n// Source: Rust DTOs in crates/core. Tests never rewrite this file.\n\n");
    for declaration in declarations {
        result.push_str("export ");
        result.push_str(&declaration);
        result.push_str("\n\n");
    }
    result
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let check = std::env::args().skip(1).any(|arg| arg == "--check");
    let destination = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../src/generated/core.ts");
    let output = declarations();
    if check {
        if fs::read_to_string(&destination)?.replace("\r\n", "\n") != output {
            return Err("Rust/TypeScript contract differs. Run npm run types:generate and review the result.".into());
        }
        println!("Rust/TypeScript contract is current");
    } else {
        fs::create_dir_all(destination.parent().unwrap())?;
        fs::write(destination, output)?;
        println!("Generated src/generated/core.ts");
    }
    Ok(())
}
