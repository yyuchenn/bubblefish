fn main() -> Result<(), Box<dyn std::error::Error>> {
    let check = std::env::args().skip(1).any(|arg| arg == "--check");
    let directory = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../src/generated");
    for (name, output) in [
        ("core.ts", declarations()),
        ("plugins.ts", plugin_declarations()),
    ] {
        let destination = directory.join(name);
        if check {
            if fs::read_to_string(&destination)?.replace("\r\n", "\n") != output {
                return Err(format!("Rust/TypeScript contract {name} differs. Run npm run types:generate and review the result.").into());
            }
        } else {
            fs::create_dir_all(destination.parent().unwrap())?;
            fs::write(destination, output)?;
            println!("Generated src/generated/{name}");
        }
    }
    if check {
        println!("Rust/TypeScript contracts are current");
    }
    Ok(())
}
